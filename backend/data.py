"""
Modular data layer.

The rest of the application only talks to this module. Two sources ship:

  DemoSource  — synthetic, generated from a known process (always available).
  RealDataSource — county-year panel built from U.S. Census ACS + OpenStreetMap
                   + a pilot NCAA roster scrape (available once
                   data/real/real_dataset.csv has been built; see realdata/).

Select with the env var  SPORTS_LAB_SOURCE = demo | real   (default: real if the
real dataset exists, else demo). Each source declares its own predictor and
outcome catalogue, so the modeling code and API never change.

Required schema (one row per community-year):
    community_id, community_name, state, year (int),
    population (int > 0), <predictor columns...>, <outcome columns...>
"""
from __future__ import annotations
import json
import os
from dataclasses import dataclass, asdict
from functools import lru_cache

import pandas as pd

DATA_DIR = os.path.join(os.path.dirname(__file__), "data")
DEMO_CSV = os.path.join(DATA_DIR, "demo_dataset.csv")
REAL_CSV = os.path.join(DATA_DIR, "real", "real_dataset.csv")
REAL_PROV = os.path.join(DATA_DIR, "real", "real_dataset_provenance.json")


@dataclass
class VariableSpec:
    key: str
    label: str
    description: str
    unit: str = ""


_SOCIO = [
    VariableSpec("median_income", "Median household income", "ACS median household income.", "USD"),
    VariableSpec("poverty_rate", "Poverty rate", "Share of population below the poverty line.", "%"),
    VariableSpec("pct_bachelors", "Education (bachelor's+)", "Share of adults 25+ with a bachelor's degree or higher.", "%"),
    VariableSpec("tennis_courts_per_100k", "Tennis access", "Tennis facilities (OSM) per 100k residents.", "courts/100k"),
    VariableSpec("pop_density", "Population density", "Residents per square mile.", "/sq mi"),
    VariableSpec("youth_population", "Youth population (0-17)",
                 "Residents under 18 — the exposure population for a youth-sport pipeline, and the "
                 "offset used by the count models (a lot closer to \"kids who could plausibly become "
                 "a D1 recruit\" than total population).", "people"),
    VariableSpec("population", "Total population", "Total community population, all ages.", "people"),
]
_NOISE = [
    VariableSpec(f"noise_{k}", f"Nuisance variable {k}", "Pure noise — included to demonstrate overfitting.", "")
    for k in range(1, 7)
]
_OUTCOMES = [
    VariableSpec("d1_players", "NCAA D1 tennis players (count)",
                 "How many NCAA Division I tennis players list a hometown in this community — "
                 "counted from scraped team rosters.", "players"),
    VariableSpec("d1_rate_per_100k", "NCAA D1 representation rate",
                 "NCAA D1 tennis players per 100,000 residents.", "players/100k"),
]


class DemoSource:
    key = "demo"
    name = "DEMO DATASET (synthetic)"
    is_real = False
    citation = ("Synthetic data generated by backend/generate_demo_data.py from a known "
                "negative-binomial process. NOT real NCAA or U.S. Census data.")
    notes = ("Six noise_* nuisance predictors are included so overfitting is observable.")

    def predictors(self): return _SOCIO + _NOISE
    def outcomes(self): return _OUTCOMES

    def load(self) -> pd.DataFrame:
        if not os.path.exists(DEMO_CSV):
            from generate_demo_data import build
            os.makedirs(DATA_DIR, exist_ok=True)
            build().to_csv(DEMO_CSV, index=False)
        return pd.read_csv(DEMO_CSV)


class RealDataSource:
    key = "real"
    name = "RESEARCH DATA (NCAA D1 tennis rosters + U.S. Census ACS + OpenStreetMap)"
    is_real = True

    def __init__(self):
        self._prov = {}
        if os.path.exists(REAL_PROV):
            try:
                self._prov = json.load(open(REAL_PROV))
            except Exception:
                self._prov = {}

    @property
    def citation(self) -> str:
        s = self._prov.get("sources", {})
        return " | ".join(f"{k}: {v}" for k, v in s.items()) or (
            "U.S. Census ACS 5-year; OpenStreetMap (ODbL); pilot ACC+Big Ten roster scrape.")

    @property
    def notes(self) -> str:
        lim = self._prov.get("limitations", [])
        return " ".join(lim)

    def predictors(self): return _SOCIO
    def outcomes(self): return _OUTCOMES

    def load(self) -> pd.DataFrame:
        if not os.path.exists(REAL_CSV):
            raise FileNotFoundError(
                "real_dataset.csv not found. Build it with:  "
                "cd backend && ./venv/bin/python -m realdata.pipeline  (no API key needed)."
            )
        return pd.read_csv(REAL_CSV, dtype={"community_id": str})


def _select_source():
    choice = os.environ.get("SPORTS_LAB_SOURCE", "").strip().lower()
    if choice == "demo":
        return DemoSource()
    if choice == "real":
        return RealDataSource()
    return RealDataSource() if os.path.exists(REAL_CSV) else DemoSource()


ACTIVE_SOURCE = _select_source()


@lru_cache(maxsize=1)
def get_dataframe() -> pd.DataFrame:
    return ACTIVE_SOURCE.load()


def predictors() -> list[VariableSpec]:
    return ACTIVE_SOURCE.predictors()


def outcomes() -> list[VariableSpec]:
    return ACTIVE_SOURCE.outcomes()


def available_years() -> list[int]:
    return sorted(int(y) for y in get_dataframe()["year"].unique())


def source_info() -> dict:
    df = get_dataframe()
    info = {
        "key": ACTIVE_SOURCE.key,
        "name": ACTIVE_SOURCE.name,
        "is_real": ACTIVE_SOURCE.is_real,
        "citation": ACTIVE_SOURCE.citation,
        "notes": getattr(ACTIVE_SOURCE, "notes", ""),
        "n_rows": int(len(df)),
        "n_communities": int(df["community_id"].nunique()),
        "years": available_years(),
        "geography": "U.S. county" if ACTIVE_SOURCE.is_real else "synthetic community",
    }
    if ACTIVE_SOURCE.is_real and getattr(ACTIVE_SOURCE, "_prov", None):
        info["provenance"] = ACTIVE_SOURCE._prov
    return info


ROSTERS_CSV = os.path.join(DATA_DIR, "real", "rosters_pilot.csv")
ROSTERS_GEOCODED_CSV = os.path.join(DATA_DIR, "real", "rosters_geocoded.csv")


@lru_cache(maxsize=1)
def geocoded_rosters() -> pd.DataFrame:
    """One row per player-season with its resolved U.S. county.

    Prefers the committed rosters_geocoded.csv; if absent (e.g. an old build),
    geocodes rosters_pilot.csv on the fly once and caches the result.
    """
    if os.path.exists(ROSTERS_GEOCODED_CSV):
        return pd.read_csv(ROSTERS_GEOCODED_CSV, dtype={"county_fips": str})
    from realdata.geocode import geocode_series

    r = pd.read_csv(ROSTERS_CSV)
    gc = geocode_series(r["hometown_raw"])
    return pd.concat(
        [r.reset_index(drop=True),
         gc[["county_fips", "county_name", "state", "match"]].rename(columns={"state": "geo_state"})],
        axis=1,
    )


def _seasons(s) -> list[int]:
    return sorted({int(x) for x in s if pd.notna(x)})


def players_search(q: str, limit: int = 60) -> dict:
    """Search roster players by name, school, or hometown."""
    if not ACTIVE_SOURCE.is_real:
        return {"available": False, "total": 0, "results": []}
    ql = (q or "").strip().lower()
    if len(ql) < 2:
        return {"available": True, "total": 0, "results": [], "query": q}

    r = geocoded_rosters()
    contains = lambda col: r[col].astype(str).str.lower().str.contains(ql, regex=False, na=False)
    hits = r[contains("player_name") | contains("school") | contains("hometown_raw")]

    grp = (
        hits.sort_values("season")
        .groupby(["player_name", "school"], as_index=False)
        .agg(
            gender=("gender", "first"),
            conference=("conference", "first"),
            hometown_raw=("hometown_raw", "first"),
            county_fips=("county_fips", "first"),
            county_name=("county_name", "first"),
            seasons=("season", _seasons),
        )
        .sort_values(["player_name", "school"])
    )
    return {
        "available": True,
        "query": q,
        "total": int(len(grp)),
        "results": grp.head(limit).where(pd.notna(grp), None).to_dict(orient="records"),
    }


_PANEL_FIELDS = ("year", "population", "youth_population", "median_income", "poverty_rate", "pct_bachelors",
                 "tennis_courts_per_100k", "pop_density", "d1_players", "d1_rate_per_100k")


def county_detail(fips: str) -> dict:
    """Everything the interactive map shows for one county: the panel row(s) by
    year plus the roster players whose hometown resolves there."""
    fips = str(fips).strip().zfill(5)
    df = get_dataframe()
    rows = df[df["community_id"].astype(str).str.zfill(5) == fips]
    if rows.empty:
        return {"found": False}

    def _num(v):
        if pd.isna(v):
            return None
        return int(v) if float(v).is_integer() else round(float(v), 3)

    by_year = [
        {k: _num(rr[k]) for k in _PANEL_FIELDS if k in rows.columns}
        for _, rr in rows.sort_values("year").iterrows()
    ]

    players: list[dict] = []
    if ACTIVE_SOURCE.is_real:
        gr = geocoded_rosters()
        pl = gr[gr["county_fips"].astype(str).str.zfill(5) == fips]
        players = (
            pl.groupby(["player_name", "school"], as_index=False)
            .agg(
                gender=("gender", "first"),
                conference=("conference", "first"),
                hometown_raw=("hometown_raw", "first"),
                seasons=("season", _seasons),
            )
            .sort_values("player_name")
            .to_dict(orient="records")
        )

    return {
        "found": True,
        "fips": fips,
        "name": str(rows.iloc[0]["community_name"]),
        "state": str(rows.iloc[0].get("state", "")),
        "by_year": by_year,
        "players": players,
        "player_count": len(players),
    }


def rosters_info(sample: int = 40) -> dict:
    """The raw NCAA roster data behind the `d1_players` outcome (real source only)."""
    if not ACTIVE_SOURCE.is_real or not os.path.exists(ROSTERS_CSV):
        return {"available": False}
    r = pd.read_csv(ROSTERS_CSV)
    df = get_dataframe()
    by_year = r.groupby("season").size().to_dict()
    return {
        "available": True,
        "description": ("One row per player-season, scraped from public NCAA Division I tennis "
                        "team roster pages. A community's `d1_players` value = the number of "
                        "these rows whose hometown geocodes to that county, that year."),
        "player_seasons": int(len(r)),
        "schools": int(r["school"].nunique()),
        "conferences": sorted(r["conference"].dropna().unique().tolist()),
        "seasons": {int(k): int(v) for k, v in sorted(by_year.items())},
        "by_gender": r["gender"].value_counts(dropna=False).to_dict(),
        "placed_in_a_us_county": int(df["d1_players"].sum()),
        "columns": list(r.columns),
        "sample": r.sample(min(sample, len(r)), random_state=1)
                   .sort_values(["season", "school"]).to_dict(orient="records"),
    }


# legacy attribute-style access (kept for any older imports)
PREDICTORS = predictors()
OUTCOMES = outcomes()
